"""Assemble every measured artifact into reports/.

Nothing in here computes a performance number. It only formats numbers that a
run already produced, so a report can never disagree with the engine. Any
metric that has not been measured is written as ``NOT YET MEASURED`` rather
than estimated, filled in, or quietly omitted.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Optional

import numpy as np
import pandas as pd

NOT_MEASURED = "NOT YET MEASURED"

SYNTHETIC_WARNING = """\
> **These performance figures come from synthetic data.**
> This environment has no market-data egress (Yahoo and Stooq both return HTTP
> 403), so the pipeline was exercised on a labelled synthetic market generated
> by `statarb.data.synthetic`. That generator builds spreads from an
> Ornstein-Uhlenbeck process with known half-lives, which is exactly the model
> the strategy assumes. **Performance measured on data drawn from the
> strategy's own assumptions is not evidence of alpha, and the Sharpe ratio
> below must not be read as one.** The synthetic run demonstrates that the
> engine is correct, the invariants hold, and the research procedure recovers
> known ground truth. Real-market metrics are marked NOT YET MEASURED and can
> be produced with the reproduction command in the README."""


def _fmt(x, nd=4):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    if isinstance(x, float):
        return f"{x:,.{nd}f}"
    if isinstance(x, (int, np.integer)):
        return f"{int(x):,}"
    return str(x)


def write_metrics_json(path: Path, *, walkforward, funnel: Dict, ablations: pd.DataFrame,
                       cost_sens: pd.DataFrame, failure_demo: pd.DataFrame,
                       engine_bench: Dict, storage_bench: Optional[Dict],
                       truth_scores: Dict, test_count: int,
                       data_meta: Dict) -> Path:
    payload = {
        "provenance": {
            "data_source": "synthetic (no market-data egress in build environment)",
            "real_market_performance": NOT_MEASURED,
            "warning": ("All performance metrics below are from synthetic data "
                        "generated by an OU process. They validate engine "
                        "correctness, not alpha."),
        },
        "dataset": data_meta,
        "research_funnel": funnel,
        "selection_vs_ground_truth": truth_scores,
        "walkforward_performance_SYNTHETIC": walkforward,
        "ablations_SYNTHETIC": ablations.to_dict(orient="records")
        if ablations is not None and len(ablations) else NOT_MEASURED,
        "cost_sensitivity_SYNTHETIC": cost_sens.to_dict(orient="records")
        if cost_sens is not None and len(cost_sens) else NOT_MEASURED,
        "failure_injection": failure_demo.to_dict(orient="records")
        if failure_demo is not None and len(failure_demo) else NOT_MEASURED,
        "engineering": {
            "backtest_engine_benchmark": engine_bench,
            "storage_benchmark": storage_bench or NOT_MEASURED,
            "tests_passing": test_count,
        },
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, default=str))
    return path


def write_research_summary(path: Path, *, funnel: Dict, truth: Dict,
                           walkforward, windows: pd.DataFrame,
                           ablations: pd.DataFrame, cost_sens: pd.DataFrame,
                           breakeven: float) -> Path:
    L = ["# Research Summary", "", SYNTHETIC_WARNING, "",
         "## 1. Research funnel", "",
         "Pair selection runs **inside each training window only**. Nothing below",
         "was computed with knowledge of the test period.", "",
         "| stage | pairs surviving |", "|---|---|"]
    for k, v in funnel.items():
        L.append(f"| {k} | {v:,} |")

    L += ["", "## 2. Selection against known ground truth", "",
          "The synthetic market is labelled, so the selection procedure can be",
          "scored rather than admired.", "",
          "| metric | value |", "|---|---|"]
    for k, v in truth.items():
        L.append(f"| {k} | {_fmt(v)} |")
    L += ["", "The decoy admission rate is the number that matters: these are",
          "pairs engineered to have *higher* return correlation than the true",
          "cointegrated pairs while sharing no equilibrium. A funnel that admits",
          "them is selecting on correlation, not cointegration.", ""]

    L += ["## 3. Walk-forward protocol", "",
          "Rolling 3y train / 1y validate / 1y test, stepping 1 year. Parameters",
          "are chosen on validation and then frozen; the test window is touched",
          "exactly once. Positions are liquidated at every window boundary so no",
          "position spans a re-fit.", "",
          "| window | train | validate | test | pairs | params | trades | net P&L |",
          "|---|---|---|---|---|---|---|---|"]
    for _, w in windows.iterrows():
        L.append(f"| {w['window']} | {w['train']} | {w['validate']} | {w['test']} | "
                 f"{w['n_pairs']} | {w['params']} | {w['n_trades']:,} | "
                 f"{w['net_pnl']:,.0f} |")

    L += ["", "## 4. Aggregate performance (SYNTHETIC)", "",
          "| metric | value |", "|---|---|"]
    for k in ["n_days", "n_trades", "cumulative_return", "cagr",
              "annualized_volatility", "sharpe", "sortino", "max_drawdown",
              "calmar", "hit_rate", "profit_factor", "avg_holding_days",
              "turnover_annual"]:
        if k in walkforward:
            L.append(f"| {k} | {_fmt(walkforward[k])} |")
    L += ["", "The Sharpe ratio here is an artifact of generating spreads from the",
          "same OU model the strategy assumes. It is reported for completeness and",
          "is **not** a performance claim.", ""]

    if ablations is not None and len(ablations):
        L += ["## 5. Ablations", "",
              "Each row removes exactly one component and re-runs the identical",
              "walk-forward protocol.", "",
              "| configuration | pairs | trades | cum. return | Sharpe | max DD | "
              "peak gross % |", "|---|---|---|---|---|---|---|"]
        for _, r in ablations.iterrows():
            L.append(f"| {r['experiment']} | {r['pairs_selected']} | "
                     f"{r['trades']:,} | {r['cumulative_return']:.4f} | "
                     f"{r['sharpe']:.2f} | {r['max_drawdown']:.4f} | "
                     f"{r['peak_gross_pct']:.1f} |")
        L += ["", "Hypotheses under test:", ""]
        for _, r in ablations.iterrows():
            if r["key"] != "baseline":
                L.append(f"- **{r['experiment']}** — {r['hypothesis']}")
        L.append("")

    if cost_sens is not None and len(cost_sens):
        L += ["## 6. Transaction-cost sensitivity", "",
              "| round-trip bps | Sharpe | cumulative return | trades | total costs |",
              "|---|---|---|---|---|"]
        for _, r in cost_sens.iterrows():
            L.append(f"| {r['total_bps']:.0f} | {r['sharpe']:.2f} | "
                     f"{r['cumulative_return']:.4f} | {int(r['trades']):,} | "
                     f"{r['total_costs']:,.0f} |")
        be = "does not break even within the tested range" if not np.isfinite(breakeven) \
            else f"**{breakeven:.1f} bps**"
        L += ["", f"Breakeven cost level: {be}.", ""]
    return _write(path, L)


def write_resume_metrics(path: Path, *, engineering: Dict, funnel: Dict,
                         truth: Dict, walkforward: Dict, ablations: pd.DataFrame,
                         test_count: int, failure_caught: str,
                         engine_bench: Optional[Dict] = None) -> Path:
    L = ["# Resume Metrics", "",
         "Every number here came from an actual run. Numbers are split into two",
         "groups, because only one group is safe to put on a resume.", "",
         "## Safe to claim: engineering and statistical scale", "",
         "These describe what was built and measured. They are reproducible and",
         "do not depend on the data being real.", "",
         "| metric | measured value |", "|---|---|"]
    for k, v in engineering.items():
        L.append(f"| {k} | {_fmt(v)} |")
    tested = funnel.get("cointegration tests run", 0)
    universe = funnel.get("all possible pairs", 0)
    L += [f"| research funnel | {universe:,} possible pairs -> {tested:,} "
          f"cointegration tests -> {funnel.get('selected', 0)} selected |",
          f"| tests passing | {test_count} |",
          f"| failure scenarios detected | {failure_caught} |",
          f"| decoy admission rate | {_fmt(truth.get('decoy_admission_rate'))} |", ""]

    L += ["## NOT safe to claim: performance", "",
          "| metric | synthetic value | real-market value |", "|---|---|---|"]
    for k in ["sharpe", "cagr", "cumulative_return", "max_drawdown", "hit_rate"]:
        if k in walkforward:
            L.append(f"| {k} | {_fmt(walkforward[k])} | {NOT_MEASURED} |")
    L += ["",
          "**Do not put the synthetic Sharpe on a resume.** It was produced on",
          "spreads generated from an Ornstein-Uhlenbeck process, which is the",
          "exact model the strategy assumes mean-reverts. The first question a",
          "desk quant will ask is 'on what data?', and the honest answer ends the",
          "conversation badly if the number is presented as alpha.", "",
          "## Suggested resume bullets", "",
          "Each of these is backed by a measured number above.", ""]
    ab_line = ""
    if ablations is not None and len(ablations):
        base = ablations[ablations["key"] == "baseline"]
        corr = ablations[ablations["key"] == "A_correlation_only"]
        if len(base) and len(corr):
            ab_line = (f"ablation showed correlation-only selection changed Sharpe "
                       f"from {float(base['sharpe'].iloc[0]):.2f} to "
                       f"{float(corr['sharpe'].iloc[0]):.2f}")
    bench = engine_bench or {}
    if bench.get("speedup"):
        bench_line = (f"a NumPy rewrite delivered a {bench['speedup']}x speedup "
                      f"({bench['reference_ms']:.0f}ms -> {bench['fast_ms']:.0f}ms) "
                      "with output verified bit-identical against the reference "
                      "implementation")
    else:
        bench_line = "engine speedup: NOT MEASURED"
    L += [
        "1. Built a statistical-arbitrage research platform in Python "
        f"({engineering.get('modules', 0)} modules, {test_count} tests): "
        f"Engle-Granger cointegration with Benjamini-Hochberg FDR control across "
        f"{funnel.get('all possible pairs', 0):,} candidate pairs, rolling-window "
        "stability screening, and a walk-forward harness with strict "
        "train/validate/test separation.",
        "",
        "2. Implemented a vectorised backtesting engine validated by "
        f"{engineering.get('accounting invariants', 0)} accounting invariants "
        "(equity-to-ledger reconciliation, cost non-negativity, pre-trade gross "
        "limits, execution-strictly-after-signal); profiling identified pandas "
        f"scalar indexing as the dominant cost, and {bench_line}.",
        "",
        "3. Built a desk monitoring layer with "
        f"{engineering.get('data validation checks', 0)} data-quality checks and "
        f"{engineering.get('reconciliation break types', 0)} trade-reconciliation "
        f"break types, proven by a failure-injection harness in which "
        f"{failure_caught} deliberately corrupted scenarios were detected"
        + (f"; {ab_line}." if ab_line else "."),
        "",
        "## One-line project title", "",
        "StatArb Desk Engine — cointegration research, walk-forward backtesting "
        "and desk monitoring for equity pairs trading (Python)", "",
        "## GitHub description (<= 150 chars)", "",
        "Statistical arbitrage research platform: cointegration + FDR pair "
        "selection, walk-forward backtesting, and desk monitoring in Python.", ""]
    return _write(path, L)


def _write(path: Path, lines) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path
